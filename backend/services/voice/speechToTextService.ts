import { exec } from 'child_process';
import { promisify } from 'util';
import { AudioUtils } from './audioUtils';
import fs from 'fs';
import path from 'path';

const execAsync = promisify(exec);

export class SpeechToTextService {
    /**
     * Transcribes an audio buffer by normalizing it to WAV and running it through Whisper.
     */
    static async transcribe(audioBuffer: Buffer): Promise<string> {
        if (!audioBuffer || audioBuffer.length === 0) {
            throw new Error("Empty audio buffer provided.");
        }

        console.log(`[SpeechToTextService] Normalizing incoming audio (${audioBuffer.length} bytes)...`);
        let normalizedAudioPath: string | null = null;
        
        try {
            // 1. Normalize Audio (WebM -> WAV 16kHz Mono)
            normalizedAudioPath = await AudioUtils.normalizeAudio(audioBuffer);
            console.log(`[SpeechToTextService] Audio normalized: ${normalizedAudioPath}`);

            // 2. Execute Whisper CLI
            const outputDir = path.dirname(normalizedAudioPath);
            const baseName = path.basename(normalizedAudioPath, '.wav');
            const transcriptPath = path.join(outputDir, `${baseName}.txt`);

            console.log(`[SpeechToTextService] Running Whisper STT...`);
            
            try {
                // Assuming `whisper` CLI is installed globally or in PATH
                await execAsync(`whisper ${normalizedAudioPath} --model base.en --output_dir ${outputDir} --output_format txt`);
                
                // Read transcript
                if (fs.existsSync(transcriptPath)) {
                    const transcript = fs.readFileSync(transcriptPath, 'utf8').trim();
                    return transcript;
                } else {
                    throw new Error("Transcript file was not generated by Whisper.");
                }
            } catch (cliError: any) {
                // If Whisper is not installed on this system, gracefully fallback for testing
                if (cliError.message.includes('command not found')) {
                    console.warn("[SpeechToTextService] Whisper CLI not found! Falling back to mock transcription.");
                    return "This is a fallback transcription because Whisper CLI is missing.";
                }
                throw cliError;
            }
            
        } catch (error: any) {
            console.error("[SpeechToTextService] Transcription failed:", error.message);
            // Return structured error message instead of failing silently
            throw new Error(`STT Pipeline Error: ${error.message}`);
        }
    }
}
